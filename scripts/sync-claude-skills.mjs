/**
 * Generate Claude Code skill entry points from the shared Antigravity skills.
 *
 *   node scripts/sync-claude-skills.mjs
 *
 * The source of truth is .agents/plugins/retro-walkthrough/skills/<name>/SKILL.md.
 * Each .claude/skills/<name>/SKILL.md is a thin wrapper with the same name and
 * description that tells Claude Code to load and follow the shared file. Re-run
 * after adding, renaming, or re-describing a skill.
 */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const srcDir = path.join(root, ".agents", "plugins", "retro-walkthrough", "skills");
const outDir = path.join(root, ".claude", "skills");
const EOL = "\r\n";

// Skills the user starts directly get an argument hint for /<name> <args>.
const ARG_HINTS = { "generate-walkthrough": "<gameId>" };

const names = fs.readdirSync(srcDir).filter((d) => fs.existsSync(path.join(srcDir, d, "SKILL.md")));
const live = new Set(names);

for (const name of names) {
  const src = fs.readFileSync(path.join(srcDir, name, "SKILL.md"), "utf-8").replace(/^﻿/, "");
  const front = src.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const description = front?.[1].match(/^description:\s*(.+)$/m)?.[1].trim();
  if (!description) throw new Error(`${name}/SKILL.md has no description in its frontmatter`);

  const rel = `.agents/plugins/retro-walkthrough/skills/${name}/SKILL.md`;
  const lines = [
    "---",
    `name: ${name}`,
    `description: ${description}`,
    ...(ARG_HINTS[name] ? [`argument-hint: "${ARG_HINTS[name]}"`] : []),
    "---",
    "",
    `<!-- Generated by scripts/sync-claude-skills.mjs. Edit ${rel} instead. -->`,
    "",
    `# ${name} (Claude Code entry point)`,
    "",
    "This skill is shared with Antigravity. Its full instructions live in one place:",
    "",
    `1. Read \`${rel}\` in full and follow it exactly. It is the authoritative version of this skill.`,
    "2. Where it names an Antigravity tool (`view_file`, `read_url_content`, `search_web`, `run_command`, `invoke_subagent`), use the Claude Code equivalent from `.agents/rules/agent-tools.md`.",
    "3. The always-on rules in `.agents/rules/` (CRLF line endings, no shortcuts) apply throughout.",
    ...(ARG_HINTS[name] ? ["", "Arguments passed to this skill: $ARGUMENTS"] : []),
    "",
  ];
  const out = path.join(outDir, name, "SKILL.md");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, lines.join(EOL), "utf-8");
  console.log(`synced ${path.relative(root, out)}`);
}

// Remove generated wrappers whose source skill no longer exists.
if (fs.existsSync(outDir)) {
  for (const d of fs.readdirSync(outDir)) {
    const f = path.join(outDir, d, "SKILL.md");
    if (!live.has(d) && fs.existsSync(f) && fs.readFileSync(f, "utf-8").includes("Generated by scripts/sync-claude-skills.mjs")) {
      fs.rmSync(path.join(outDir, d), { recursive: true });
      console.log(`removed stale .claude/skills/${d}`);
    }
  }
}
